#!/usr/bin/env python3
"""Generates lib/ui/shell/wanqi_glyph.g.dart from assets/brand/wanqi-ring.svg and
assets/brand/wanqi-star.svg.

Run from app/:

    python3 tool/make_wanqi_mark.py

The two masters are plain SVG in the launcher icon's 108 grid (one `M ... C ... Z`
subpath each, traced from the 1024px icon master). Their siblings in the same
folder — wanqi-mark.svg (disc + ring + star), wanqi-mark-light.svg (the light
colorway), wanqi-mark-fg.svg (ring + star on transparent), wanqi-mark-mono.svg,
wanqi-bg.svg, wanqi-ring-dark.svg — are for non-Flutter uses (site, docs, design).
"""
import os
import re

import make_brand_mark as brand

APP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(APP, 'assets', 'brand')
OUT = os.path.join(APP, 'lib', 'ui', 'shell', 'wanqi_glyph.g.dart')


def path_of(name):
    svg = open(os.path.join(SRC, name), encoding='utf-8').read()
    d = re.search(r'<path [^>]*?d="([^"]+)"', svg).group(1)
    return brand.parse_d(d)


def bbox(subs):
    xs, ys = [], []
    for (x, y), segs in subs:
        cur = (x, y)
        xs.append(x); ys.append(y)
        for c1, c2, p3 in segs:
            for t in (0.0, 0.25, 0.5, 0.75, 1.0):
                px, py = brand.bez(cur, c1, c2, p3, t)
                xs.append(px); ys.append(py)
            cur = p3
    return min(xs), min(ys), max(xs), max(ys)


ring = path_of('wanqi-ring.svg')
star = path_of('wanqi-star.svg')
rb, sb = bbox(ring), bbox(star)
ink = (min(rb[0], sb[0]), min(rb[1], sb[1]), max(rb[2], sb[2]), max(rb[3], sb[3]))


def rect(b):
    return f'Rect.fromLTRB({brand.f(b[0])}, {brand.f(b[1])}, {brand.f(b[2])}, {brand.f(b[3])})'


def dart_path(subs):
    lines = ['Path()']
    for (x, y), segs in subs:
        lines.append(f'    ..moveTo({brand.f(x)}, {brand.f(y)})')
        for c1, c2, p3 in segs:
            lines.append('    ..cubicTo(' + ', '.join(brand.f(v) for p in (c1, c2, p3) for v in p) + ')')
        lines.append('    ..close()')
    return '\n'.join(lines)


text = f'''// GENERATED by tool/make_wanqi_mark.py from assets/brand/wanqi-ring.svg and
// wanqi-star.svg. Do not edit; change the masters and run the tool.
//
// 万器 glyph in the launcher icon's 108 grid: the infinity ring and the four-point
// star, traced from the 1024px icon master (ios-icon-work/AppIcon-1024.png).

// dart format off
import 'dart:ui' show Path, Rect;

/// Paths and measurements of the 万器 mark (see `wanqi_mark.dart`).
abstract final class WanqiGlyph {{
  /// The icon's 108-unit grid; the paths are in these units.
  static const grid = 108.0;

  /// The ring's ink box (thin left loops, thick right loop, weave gaps included).
  static const ringBox = {rect(rb)};

  /// The star's ink box.
  static const starBox = {rect(sb)};

  /// Ring + star.
  static const inkBox = {rect(ink)};

  /// The silver / navy infinity ring.
  static final Path ring = {dart_path(ring).replace(chr(10), chr(10) + '  ')};

  /// The gold four-point star.
  static final Path star = {dart_path(star).replace(chr(10), chr(10) + '  ')};
}}
'''

os.makedirs(os.path.dirname(OUT), exist_ok=True)
with open(OUT, 'w', encoding='utf-8') as f:
    f.write(text)
print(f'wrote {OUT} ({len(text)} bytes)')
